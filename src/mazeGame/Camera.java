package mazeGame;

public class Camera
{
	//-----------------------------------------------------------------------//
	
	static int x = 0;
	static int y = 0;
	static int z = 0;
	
	//-----------------------------------------------------------------------//
	
	public static void setLocation(int x, int y, int z)
	{
		Camera.x = x;
		Camera.y = y;
		Camera.z = z;
	}
	
	//-----------------------------------------------------------------------//
	
	public static void moveLT(int dx)
	{
		x -= dx;
	}
	
	//-----------------------------------------------------------------------//
	
	public static void moveRT(int dx)
	{
		x += dx;
	}
	
	//-----------------------------------------------------------------------//
	
	public static void moveUP(int dy)
	{
		y -= dy;
	}
	
	//-----------------------------------------------------------------------//
	
	public static void moveDN(int dy)
	{
		y += dy;
	}
	
	//-----------------------------------------------------------------------//
	
	public static void moveFW(int dz)
	{
		z += dz;
	}
	
	//-----------------------------------------------------------------------//
	
	public static void moveBW(int dz)
	{
		z -= dz;
	}

	//-----------------------------------------------------------------------//

}